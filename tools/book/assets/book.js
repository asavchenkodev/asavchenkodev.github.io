/* Book behaviour shared by the home page and every chapter (guides/book/assets/book.js).
   Needs assets/book-data.js (window.BOOK, generated by tools/build_book.py) loaded before it.
   - renders math written as \( … \) and \[ … \] when KaTeX is on the page (before marks.js anchors marks);
   - chapter pages: "Book" link and part/chapter line in the contents, previous/next chapter at the end;
   - search over all chapters (Search button, "/" or Ctrl+K), index loaded on first use;
   - home page: marks per chapter, export/import of all marks. */
(function () {
  'use strict';
  const script = document.currentScript;
  const ROOT = script ? script.src.replace(/assets\/book\.js(\?.*)?$/, '') : '';
  const BOOK = window.BOOK || { parts: [], chapters: [] };
  const meta = n => { const m = document.querySelector('meta[name="' + n + '"]'); return m ? m.content : ''; };
  const SLUG = meta('guide-id');
  const isHome = document.body && document.body.dataset.page === 'home';
  const esc = s => String(s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  const get = k => { try { return localStorage.getItem(k); } catch (e) { return null; } };
  const set = (k, v) => { try { localStorage.setItem(k, v); } catch (e) { /* storage unavailable */ } };
  const json = (k, d) => { try { return JSON.parse(get(k) || '') || d; } catch (e) { return d; } };
  const chapters = BOOK.chapters || [];
  const bySlug = Object.fromEntries(chapters.map(c => [c.slug, c]));
  const href = (slug, id) => ROOT + 'ch/' + slug + '.html' + (id ? '#' + id : '');

  /* ---------- math: runs now, while deferred scripts execute, so marks.js sees the final text ---------- */
  const doc = document.querySelector('.g-doc');
  if (doc && window.renderMathInElement) {
    try {
      window.renderMathInElement(doc, {
        delimiters: [{ left: '\\[', right: '\\]', display: true }, { left: '\\(', right: '\\)', display: false }],
        throwOnError: false, ignoredTags: ['script', 'noscript', 'style', 'textarea', 'pre', 'code', 'option']
      });
    } catch (e) { console.warn('math', e); }
  }

  /* ---------- chapter page chrome (after guide.js has built the contents) ---------- */
  function chapterChrome() {
    const ch = bySlug[SLUG];
    if (!ch) return;
    const part = (BOOK.parts || []).find(p => p.id === ch.part);
    const toc = document.querySelector('.g-toc');
    if (toc && !toc.querySelector('.b-nav')) {
      const nav = document.createElement('div');
      nav.className = 'b-nav';
      nav.setAttribute('data-no-mark', '');
      nav.innerHTML = '<a class="b-home" href="' + ROOT + 'index.html">← ' + esc(BOOK.short || 'Book') + '</a>' +
        '<div class="b-where">' + (part ? 'Part ' + esc(part.num) + ' · ' + esc(part.title) + '<br>' : '') +
        'Chapter ' + ch.num + ' · ' + esc(ch.title) + '</div>';
      toc.insertBefore(nav, toc.firstChild);
    }
    const kicker = document.querySelector('.g-title .kicker');
    if (kicker) kicker.textContent = 'Chapter ' + ch.num + (part ? ' · ' + part.title : '');
    const i = chapters.indexOf(ch);
    const prev = chapters[i - 1], next = chapters[i + 1];
    const pager = document.createElement('nav');
    pager.className = 'b-pager';
    pager.setAttribute('data-no-mark', '');
    pager.innerHTML =
      (prev ? '<a class="prev" href="' + href(prev.slug) + '"><small>← Chapter ' + prev.num + '</small>' + esc(prev.title) + '</a>' : '') +
      (next ? '<a class="next" href="' + href(next.slug) + '"><small>Chapter ' + next.num + ' →</small>' + esc(next.title) + '</a>' : '') +
      '<a class="up" href="' + ROOT + 'index.html">Book contents</a>';
    if (doc) doc.appendChild(pager);
    if (!document.title.includes('·')) document.title = ch.title + ' · ' + (BOOK.short || 'Book');
  }

  /* ---------- search ---------- */
  let overlay, input, results, sel = -1, loading = null;
  function loadIndex() {
    if (window.BOOK_SEARCH) return Promise.resolve(window.BOOK_SEARCH);
    if (loading) return loading;
    loading = new Promise((res, rej) => {
      const s = document.createElement('script');
      s.src = ROOT + 'assets/search-index.js';
      s.onload = () => res(window.BOOK_SEARCH || []);
      s.onerror = rej;
      document.head.appendChild(s);
    });
    return loading;
  }
  function buildSearch() {
    overlay = document.createElement('div');
    overlay.className = 'b-search gm-ui';
    overlay.setAttribute('data-no-mark', '');
    overlay.innerHTML = '<div class="b-search-box" role="dialog" aria-label="Search the book">' +
      '<input type="search" placeholder="Search all chapters…" autocomplete="off" spellcheck="false">' +
      '<div class="b-results"></div><div class="b-search-hint">↑ ↓ to move · Enter to open · Esc to close · all words must match</div></div>';
    document.body.appendChild(overlay);
    input = overlay.querySelector('input');
    results = overlay.querySelector('.b-results');
    overlay.addEventListener('click', e => { if (e.target === overlay) closeSearch(); });
    input.addEventListener('input', () => run(input.value));
    input.addEventListener('keydown', e => {
      const items = results.querySelectorAll('a');
      if (e.key === 'ArrowDown' || e.key === 'ArrowUp') {
        e.preventDefault();
        sel = Math.max(0, Math.min(items.length - 1, sel + (e.key === 'ArrowDown' ? 1 : -1)));
        items.forEach((a, j) => a.classList.toggle('sel', j === sel));
        if (items[sel]) items[sel].scrollIntoView({ block: 'nearest' });
      } else if (e.key === 'Enter' && items.length) {
        e.preventDefault();
        (items[sel >= 0 ? sel : 0]).click();
      } else if (e.key === 'Escape') closeSearch();
    });
  }
  function openSearch(q) {
    if (!overlay) buildSearch();
    overlay.classList.add('open');
    input.value = q || input.value;
    input.focus();
    input.select();
    loadIndex().then(() => run(input.value)).catch(() => {
      results.innerHTML = '<div class="r-none">Search index not found (assets/search-index.js). Run tools/build_book.py.</div>';
    });
  }
  function closeSearch() { if (overlay) overlay.classList.remove('open'); }
  const norm = s => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');
  function run(q) {
    const idx = window.BOOK_SEARCH;
    if (!idx) return;
    const terms = norm(q).split(/\s+/).filter(t => t.length > 1 || /\d/.test(t));
    sel = -1;
    if (!terms.length) { results.innerHTML = ''; return; }
    const hits = [];
    for (const e of idx) {
      if (!e._t) { e._t = norm(e.t); e._x = norm(e.x); }
      let score = 0, ok = true;
      for (const t of terms) {
        const inT = e._t.includes(t), inX = e._x.includes(t);
        if (!inT && !inX) { ok = false; break; }
        score += (inT ? 10 : 0) + (inX ? 1 + Math.min(4, e._x.split(t).length - 2) * 0.25 : 0);
      }
      if (ok) hits.push([score, e]);
    }
    hits.sort((a, b) => b[0] - a[0]);
    if (!hits.length) { results.innerHTML = '<div class="r-none">No matches.</div>'; return; }
    const re = new RegExp('(' + terms.map(t => t.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|') + ')', 'gi');
    results.innerHTML = hits.slice(0, 60).map(([, e]) => {
      const c = bySlug[e.c];
      const i = e._x.indexOf(terms.find(t => e._x.includes(t)) || '');
      const start = Math.max(0, i - 60);
      const snip = (start ? '…' : '') + e.x.slice(start, start + 200) + (e.x.length > start + 200 ? '…' : '');
      return '<a href="' + href(e.c, e.id) + '"><div class="r-t">' + (e.n ? esc(e.n) + ' ' : '') + esc(e.t).replace(re, '<mark>$1</mark>') + '</div>' +
        '<div class="r-c">' + (c ? 'Chapter ' + c.num + ' · ' + esc(c.title) : esc(e.c)) + '</div>' +
        (i >= 0 ? '<div class="r-x">' + esc(snip).replace(re, '<mark>$1</mark>') + '</div>' : '') + '</a>';
    }).join('');
  }
  document.addEventListener('keydown', e => {
    const typing = e.target.closest && e.target.closest('input, textarea, [contenteditable]');
    if ((e.key === '/' && !typing) || ((e.ctrlKey || e.metaKey) && e.key.toLowerCase() === 'k')) {
      e.preventDefault();
      openSearch();
    }
  });

  function searchButton() {
    const bar = document.querySelector('.g-bar');
    if (!bar || bar.querySelector('.b-sbtn')) return;
    const b = document.createElement('button');
    b.type = 'button';
    b.className = 'b-sbtn';
    b.title = 'Search all chapters ( / )';
    b.textContent = 'Search';
    b.addEventListener('click', () => openSearch());
    bar.insertBefore(b, bar.firstChild);
  }

  /* ---------- home page ---------- */
  const TAGS = { unclear: 'Unclear', complex: 'Complex', note: 'Note' };
  function marksOf(slug) {
    const d = json('guide-marks:' + slug, []);
    return Array.isArray(d) ? d : (d.marks || []);
  }
  function home() {
    stats();
    const q = document.querySelector('.b-q');
    if (q) q.addEventListener('click', () => openSearch());
    const box = document.querySelector('.b-marks');
    if (!box) return;
    box.querySelector('[data-act=export]').addEventListener('click', exportAll);
    box.querySelector('[data-act=copy]').addEventListener('click', copyAll);
    const file = box.querySelector('input[type=file]');
    box.querySelector('[data-act=import]').addEventListener('click', () => file.click());
    file.addEventListener('change', () => { if (file.files[0]) importAll(file.files[0]); file.value = ''; });
  }
  function stats() {
    document.querySelectorAll('[data-slug]').forEach(row => {
      const n = marksOf(row.dataset.slug).length;
      const stat = row.querySelector('.stat .t');
      if (stat) stat.textContent = n ? n + ' mark' + (n > 1 ? 's' : '') : '';
    });
    renderMarks();
  }
  function allMarks() {
    return chapters.map(c => {
      return { guide: { id: c.slug, title: c.title, file: 'ch/' + c.slug + '.html' }, marks: marksOf(c.slug) };
    }).filter(c => c.marks.length);
  }
  function renderMarks() {
    const list = document.querySelector('.b-mlist');
    if (!list) return;
    const all = allMarks().filter(c => c.marks.length);
    const total = all.reduce((s, c) => s + c.marks.length, 0);
    document.querySelector('.b-marks h2').textContent = 'Marks' + (total ? ' (' + total + ')' : '');
    if (!total) {
      list.innerHTML = '<p class="b-foot">No marks yet. In any chapter, select a word, phrase or line and tag it Unclear, Complex or Note. ' +
        'All marks are collected here for export.</p>';
      return;
    }
    list.innerHTML = all.map(c => '<div class="b-mch">Chapter ' + (bySlug[c.guide.id] || {}).num + ' · ' + esc(c.guide.title) + '</div>' +
      c.marks.map(m => '<a class="b-mi" href="' + href(c.guide.id, m.section) + '"><span class="gm-dot gm-c-' + esc(m.tag) + '"></span>' +
        '<b>' + esc(TAGS[m.tag] || m.tag) + '</b> ' + esc((m.section_num ? m.section_num + ' ' : '') + (m.section_title || '')) +
        '<span class="c">“' + esc(m.quote.replace(/\s+/g, ' ').slice(0, 160)) + '”' + (m.comment ? ' — ' + esc(m.comment) : '') + '</span></a>').join('')
    ).join('');
  }
  function download(name, text) {
    const a = document.createElement('a');
    a.href = URL.createObjectURL(new Blob([text], { type: 'application/json' }));
    a.download = name;
    document.body.appendChild(a); a.click(); a.remove();
    setTimeout(() => URL.revokeObjectURL(a.href), 2000);
  }
  async function exportAll() {
    const data = JSON.stringify({ format: 'book-marks/1', book: BOOK.title, exported: new Date().toISOString(), chapters: allMarks() }, null, 2);
    const name = 'book-' + new Date().toISOString().slice(0, 10) + '.marks.json';
    if (window.showSaveFilePicker) {
      try {
        const h = await window.showSaveFilePicker({ suggestedName: name, id: 'guide-marks', types: [{ description: 'Book marks', accept: { 'application/json': ['.json'] } }] });
        const w = await h.createWritable(); await w.write(data); await w.close(); return;
      } catch (e) { if (e && e.name === 'AbortError') return; }
    }
    download(name, data);
  }
  async function copyAll() {
    const lines = [];
    allMarks().filter(c => c.marks.length).forEach(c => {
      lines.push('## ' + c.guide.title + ' (' + c.guide.file + ')');
      c.marks.forEach((m, i) => lines.push((i + 1) + '. [' + m.tag + '] ' + ((m.section_num || '') + ' ' + (m.section_title || '')).trim() +
        ': "' + m.quote.replace(/\s+/g, ' ') + '"' + (m.comment ? '\n   Comment: ' + m.comment : '')));
      lines.push('');
    });
    try { await navigator.clipboard.writeText(lines.join('\n')); } catch (e) { /* clipboard blocked */ }
  }
  function importAll(f) {
    const r = new FileReader();
    r.onload = () => {
      let d; try { d = JSON.parse(r.result); } catch (e) { return; }
      const groups = d.format === 'book-marks/1' ? d.chapters : [{ guide: d.guide, marks: d.marks || [] }];
      groups.forEach(g => {
        if (!g || !g.guide || !g.guide.id) return;
        const cur = marksOf(g.guide.id);
        (g.marks || []).forEach(m => {
          if (!m || !m.id) return;
          const x = Object.assign({}, m); delete x.found;
          const i = cur.findIndex(c => c.id === x.id);
          if (i < 0) cur.push(x); else if ((x.updated || '') > (cur[i].updated || '')) cur[i] = x;
        });
        set('guide-marks:' + g.guide.id, JSON.stringify(cur));
      });
      stats();
    };
    r.readAsText(f);
  }

  function init() {
    if (isHome) home();
    else chapterChrome();
    searchButton();
  }
  // run after guide.js (registered later, so wait one tick)
  const later = () => setTimeout(init, 0);
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', later);
  else later();
  window.Book = { openSearch, href };
})();
